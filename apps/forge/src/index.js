import ResolverModule from "@forge/resolver";
import { resolveResolver } from "./forge-interop.js";
import { issueHint } from "./security-context.js";
import { saveCurrentReview, refreshSavedReview, prepareReadOnlyReport, approveReadOnlyReport, generateReadOnlyReport, revokeReadOnlyReport, prepareDemoComment, approveDemoComment, executeDemoComment, revokeDemoComment, reconcileDemoComment, readSavedGraph, revalidateSavedReview, budgetedRead, budgetedPreview, runSyntheticProvider, getSafetySettings, recoverSavedReport } from "./state/forge-review.js";
import {projectDashboard} from "./dashboard/forge-project.js";
const Resolver = resolveResolver(ResolverModule);
const resolver = new Resolver();
// Extension issue key is a hint, never a grant. Jira asUser enforces access.
// No client-provided tenant, issue key, scopes, approval or URL is trusted.
resolver.define("getPanelContext", ({ context }) => issueHint(context));
resolver.define("readCurrentIssue", ({ context }) => budgetedRead(context));
resolver.define("previewIntent", ({ context, payload }) => budgetedPreview(context, payload?.intent));
resolver.define("saveCurrentReview", ({context,payload})=>saveCurrentReview(context,payload?.intent));
resolver.define("refreshSavedReview", ({context,payload})=>refreshSavedReview(context,payload?.review_id));
resolver.define("prepareReadOnlyReport",({context,payload})=>prepareReadOnlyReport(context,payload?.review_id));
resolver.define("approveReadOnlyReport",({context,payload})=>approveReadOnlyReport(context,payload?.request_id,payload?.expected_digest));
resolver.define("generateReadOnlyReport",({context,payload})=>generateReadOnlyReport(context,payload?.request_id));
resolver.define("revokeReadOnlyReport",({context,payload})=>revokeReadOnlyReport(context,payload?.request_id));
resolver.define("prepareDemoComment",({context,payload})=>prepareDemoComment(context,payload?.review_id));
resolver.define("approveDemoComment",({context,payload})=>approveDemoComment(context,payload?.request_id,payload?.expected_digest));
resolver.define("executeDemoComment",({context,payload})=>executeDemoComment(context,payload?.request_id));
resolver.define("revokeDemoComment",({context,payload})=>revokeDemoComment(context,payload?.request_id));
resolver.define("reconcileDemoComment",({context,payload})=>reconcileDemoComment(context,payload?.request_id));
resolver.define("readSavedGraph",({context,payload})=>readSavedGraph(context,payload?.review_id));
resolver.define("revalidateSavedReview",({context,payload})=>revalidateSavedReview(context,payload?.review_id));
resolver.define("getSafetySettings",({context})=>getSafetySettings(context));
resolver.define("runSyntheticProvider",({context,payload})=>runSyntheticProvider(context,payload));
resolver.define("recoverSavedReport",({context,payload})=>recoverSavedReport(context,payload?.review_id));
export const handler = resolver.getDefinitions();
const projectResolver=new Resolver();
projectResolver.define("readProjectDashboard",({context})=>projectDashboard(context));
export const projectHandler=projectResolver.getDefinitions();
